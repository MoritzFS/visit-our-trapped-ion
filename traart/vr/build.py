"""Assemble trap_vr.html from source.

    python3 build.py

Inputs, all beside this file:

    body.html                 the page: markup, CSS, and the app module, with
                              /*__PLACEHOLDER__*/ slots for everything below
    vendor/three.module.min.js  three r160, ES module build
    vendor/VRButton.js          three's addon, unmodified
    vendor/fonts.css            IBM Plex latin subsets as @font-face data URIs
    trapmesh.js               generated by tools/step_to_mesh.py
    vrscore.json              generated by tools/export_vrscore.py

Output: trap_vr.html -- one file, no network, no build step at run time. It
works from a file:// URL, off a USB stick, or off any static host. (WebXR only
enters immersive mode from https:// or localhost, so for the headset it has to
come off a real host; see README.)

three's ES module ends in `export { A as B, ... }`, which cannot appear inside
a page's own module. The export list is rewritten into `const THREE = {...}`
with the same names, and the app is wrapped in a block so its bindings cannot
collide with three's minified top-level names.
"""
import os
import re

HERE = os.path.dirname(os.path.abspath(__file__)) or "."
p = lambda *a: os.path.join(HERE, *a)

body = open(p("body.html")).read()
mesh = open(p("trapmesh.js")).read()
score = open(p("vrscore.json")).read().strip()

meta = re.search(r"export const TRAP_META = (.*?);\n", mesh, re.S).group(1)
pos = re.search(r'TRAP_POS_B64 = "(.*?)"', mesh, re.S).group(1)
idx = re.search(r'TRAP_IDX_B64 = "(.*?)"', mesh, re.S).group(1)

# --- three.js: ES export list -> a plain THREE namespace object -------------
three = open(p("vendor", "three.module.min.js")).read().rstrip()
m = re.search(r"export\s*\{([^{}]*)\};?\s*$", three, re.S)
if not m:
    raise SystemExit("no trailing export statement in three.module.min.js")
pairs = []
for item in m.group(1).split(","):
    item = item.strip()
    if not item:
        continue
    local, _, exported = item.partition(" as ")
    pairs.append("%s:%s" % ((exported or local).strip(), local.strip()))
three = ("/* three.js r160 -- MIT (c) 2010-2024 three.js authors. Inlined so the\n"
         "   page needs no network at all. */\n"
         + three[:m.start()] + "const THREE={" + ",".join(pairs) + "};")

fonts = open(p("vendor", "fonts.css")).read()

vrb = open(p("vendor", "VRButton.js")).read().rstrip()
vrb = "/* three.js addons -- VRButton (MIT) */\n" + \
      re.sub(r"export\s*\{\s*VRButton\s*\};?\s*$", "", vrb)

out = (body.replace("/*__FONTS__*/", fonts)
           .replace("/*__THREE__*/", three)
           .replace("/*__VRBUTTON__*/", vrb)
           .replace("/*__TRAP_META__*/", meta)
           .replace("/*__TRAP_POS__*/", pos)
           .replace("/*__TRAP_IDX__*/", idx)
           .replace("/*__SCORE__*/", score))
for left in ("/*__FONTS", "/*__THREE", "/*__VRBUTTON", "/*__TRAP", "/*__SCORE"):
    assert left not in out, "placeholder %s not filled" % left

head, tail = out.split('\n<div id="gate">', 1)
open(p("trap_vr.html"), "w").write(
    '<!doctype html>\n<html lang="en">\n<head>\n<meta charset="utf-8">\n'
    '<meta name="viewport" content="width=device-width,initial-scale=1,'
    'viewport-fit=cover">\n' + head +
    '\n</head>\n<body>\n<div id="gate">' + tail + "\n</body>\n</html>\n")

# the same page without the document shell, for publishing as an Artifact
open(p("trap_vr.artifact.html"), "w").write(out)

for f in ("trap_vr.html", "trap_vr.artifact.html"):
    print("%-24s %.2f MB" % (f, os.path.getsize(p(f)) / 1e6))
