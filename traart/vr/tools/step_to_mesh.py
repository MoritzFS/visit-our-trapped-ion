"""GKP_trap.stp  ->  trapmesh.js  (base64 positions + indices for the VR page).

Two steps, both cheap:

  1. gmsh reads the STEP through OpenCASCADE and meshes every CAD *face*
     separately.  Coarse limits on the flats, fine limits from curvature, so
     the 18.9 x 10 mm plate costs a few hundred triangles while the segmented
     electrode fingers along the slot keep their notches.  ~11k triangles.

  2. The mesh is recentred on the ion and rotated into the app's frame:

         world +X = CAD +z    along the slot
         world +Y = CAD +x    up  (the plate's long axis, as asked)
         world +Z = CAD +y    through the plate

     Positions stay in millimetres; the page applies the magnification as a
     group scale, so `scaleX` in the page is literally "mm of trap per mm of
     world x 1000".

The ion origin is the centre of the through-slot that carries the segmented
electrodes.  It was measured, not guessed: rays cast along CAD y over a grid
in the x-z plane give exactly two open regions in that end of the plate, and
the electrode one is

     x in [3.0464, 3.6079]   ->  gap    0.5615 mm   (vertical in the app)
     z in [-2.2575, 2.2575]  ->  length 4.5150 mm
     y : through the full    ->  depth  2.2500 mm
         2.25 mm thickness

Requires: gmsh, trimesh, numpy  (pip install gmsh trimesh; gmsh also wants
libGLU / libXft present).
"""
from __future__ import annotations

import base64
import json
import sys

import numpy as np
import trimesh

STEP = sys.argv[1] if len(sys.argv) > 1 else "GKP_trap.stp"
OUT = sys.argv[2] if len(sys.argv) > 2 else "trapmesh.js"
STL = "trap_vr.stl"

ION = np.array([3.32715, -5.449592, 0.0])       # slot centre, CAD millimetres


def mesh_step(path: str, stl: str) -> None:
    import gmsh
    gmsh.initialize()
    gmsh.option.setNumber("General.Terminal", 0)
    gmsh.merge(path)
    gmsh.option.setNumber("Mesh.MeshSizeMin", 0.03)
    gmsh.option.setNumber("Mesh.MeshSizeMax", 1.6)
    gmsh.option.setNumber("Mesh.MeshSizeFromCurvature", 14)
    gmsh.option.setNumber("Mesh.MeshSizeExtendFromBoundary", 0)
    gmsh.option.setNumber("Mesh.MeshSizeFromPoints", 0)
    gmsh.option.setNumber("Mesh.Algorithm", 6)
    gmsh.model.mesh.generate(2)
    gmsh.write(stl)
    gmsh.finalize()


def pack(stl: str, out: str) -> None:
    m = trimesh.load(stl)
    m.merge_vertices()
    V = np.asarray(m.vertices, dtype=np.float64)
    F = np.asarray(m.faces, dtype=np.int64)
    if V.shape[0] >= 65535:
        raise SystemExit("more than 65535 vertices: widen the index type or "
                         "raise Mesh.MeshSizeMax")

    v = V - ION
    W = np.stack([v[:, 2], v[:, 0], v[:, 1]], axis=1).astype(np.float32)

    meta = {
        "verts": int(V.shape[0]), "tris": int(F.shape[0]),
        "bounds": [[float(x) for x in W.min(0)], [float(x) for x in W.max(0)]],
        "slot": {"gap_mm": 0.5615, "len_mm": 4.515, "depth_mm": 2.25},
    }
    with open(out, "w") as fh:
        fh.write("// generated by tools/step_to_mesh.py -- do not hand-edit\n")
        fh.write("// units: millimetres, origin at the ion, +Y up\n")
        fh.write("export const TRAP_META = %s;\n" % json.dumps(meta))
        fh.write('export const TRAP_POS_B64 = "%s";\n'
                 % base64.b64encode(W.astype("<f4").tobytes()).decode())
        fh.write('export const TRAP_IDX_B64 = "%s";\n'
                 % base64.b64encode(F.astype("<u2").tobytes()).decode())
    print(json.dumps(meta))


if __name__ == "__main__":
    mesh_step(STEP, STL)
    pack(STL, OUT)
